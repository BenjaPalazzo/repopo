//! Generic result request endpoints.
//!
//! All result types go through the same two endpoints:
//!
//! ```text
//! POST /jobs/:id/results          — enqueue a result request
//! GET  /jobs/:id/results/:req_id  — poll state or download completed file
//! ```
//!
//! ## Velocity fast-path
//!
//! The scheduler generates `velocity.png` automatically as the final step of
//! every job. If the file already exists on disk when `POST /jobs/:id/results`
//! is called with `result_type = "velocity"`, it is served immediately without
//! enqueuing anything.
//!
//! ## Async path (all other types, and velocity when file is absent)
//!
//! A `result_request` row is inserted in `queued` state and its ID is returned.
//! The results scheduler loop picks it up, runs the Docker container, and marks
//! it `completed` or `failed`. The client polls `GET /jobs/:id/results/:req_id`
//! until the state is terminal, then the completed file is streamed back.

use std::path::PathBuf;

use axum::{
    extract::{Path, State},
    http::{StatusCode, header},
    response::{IntoResponse, Response},
    Json,
};
use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use uuid::Uuid;

use shared::models::{JobState, ResultState, ResultType};
use shared::queries::{enqueue_result_request, get_job, get_result_request};

use crate::auth::InterfaceToken;
use crate::error::{AppError, ApiResult};
use crate::AppState;

// =============================================================================
// Request / response types
// =============================================================================

/// Body of `POST /jobs/:id/results`.
#[derive(Deserialize)]
pub struct ResultRequestBody {
    /// One of: `"velocity"`, `"timeseries"`, `"ai_summary"`, `"dem"`, `"3d_model"`.
    pub result_type: String,

    /// Type-specific parameters.
    ///
    /// - `"timeseries"`: `{ "lat": <f64>, "lon": <f64> }` — required.
    /// - Others: omit or pass `null`.
    pub params: Option<serde_json::Value>,
}

/// Response from `POST /jobs/:id/results` when a new request is enqueued.
#[derive(Serialize)]
pub struct EnqueueResultResponse {
    pub result_request_id: Uuid,
    pub state: String,
}

/// Response from `GET /jobs/:id/results/:req_id` when the request is not yet
/// completed.
#[derive(Serialize)]
pub struct ResultStatusResponse {
    pub result_request_id: Uuid,
    pub job_id:            Uuid,
    pub result_type:       String,
    pub state:             String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub error:             Option<String>,
    pub created_at:        DateTime<Utc>,
    pub updated_at:        DateTime<Utc>,
}

// =============================================================================
// POST /jobs/:id/results
// =============================================================================

/// Enqueues a result generation request for the given job.
///
/// Velocity fast-path: if `velocity.png` already exists on disk, returns it
/// immediately (200) without writing to `result_requests`.
pub async fn enqueue_result(
    _token: InterfaceToken,
    Path(job_id): Path<Uuid>,
                            State(state): State<AppState>,
                            Json(body): Json<ResultRequestBody>,
) -> ApiResult<Response> {
    // Resolve result type.
    let result_type = ResultType::from_str(&body.result_type).ok_or_else(|| {
        AppError::Validation(format!(
            "unknown result_type '{}'; valid: velocity, timeseries, ai_summary, dem, 3d_model",
            body.result_type
        ))
    })?;

    // Validate type-specific params.
    validate_params(result_type, &body.params)?;

    // Verify job exists and is completed.
    let job = get_job(&state.pool, job_id)
    .await?
    .ok_or(AppError::JobNotFound)?;

    if !matches!(job.state, JobState::Completed) {
        return Err(AppError::Validation(
            "job is not completed; results can only be requested for completed jobs".to_string(),
        ));
    }

    // Velocity fast-path: serve from disk if already generated by the scheduler.
    if result_type == ResultType::Velocity {
        let velocity_path = PathBuf::from(&job.work_dir)
        .join("results")
        .join("velocity.png");

        if velocity_path.exists() {
            let bytes = tokio::fs::read(&velocity_path)
            .await
            .map_err(|e| AppError::Internal(format!("reading velocity.png: {e}")))?;

            return Ok((
                StatusCode::OK,
                [(header::CONTENT_TYPE, "image/png")],
                       bytes,
            )
            .into_response());
        }
        // File absent: fall through and enqueue.
    }

    // Enqueue result request (work_dir = None: scheduler resolves via jobs table).
    let req = enqueue_result_request(&state.pool, Some(job_id), result_type, body.params, None)
    .await
    .map_err(|e| AppError::Internal(format!("enqueue_result_request: {e}")))?;

    Ok((
        StatusCode::ACCEPTED,
        Json(EnqueueResultResponse {
            result_request_id: req.id,
            state:             req.state.as_str().to_string(),
        }),
    )
    .into_response())
}

// =============================================================================
// GET /jobs/:id/results/:request_id
// =============================================================================

/// Returns the state of a result request, or streams the output file if done.
///
/// - `queued` / `running` / `failed` → JSON status (200)
/// - `completed` → file bytes with correct MIME (200)
pub async fn get_result(
    _token: InterfaceToken,
    Path((job_id, request_id)): Path<(Uuid, Uuid)>,
                        State(state): State<AppState>,
) -> ApiResult<Response> {
    let req = get_result_request(&state.pool, request_id)
    .await
    .map_err(|e| AppError::Internal(format!("get_result_request: {e}")))?
    .ok_or_else(|| AppError::ResultNotFound("result request not found".to_string()))?;

    // Validate cross-job ownership.
    // FIX: req.job_id is Option<Uuid> (NULL for demo requests), so compare with Some(job_id).
    if req.job_id != Some(job_id) {
        return Err(AppError::ResultNotFound(
            "result request does not belong to this job".to_string(),
        ));
    }

    match req.state {
        ResultState::Completed => {
            let job = get_job(&state.pool, job_id)
            .await?
            .ok_or(AppError::JobNotFound)?;

            let results_dir = PathBuf::from(&job.work_dir).join("results");

            let file_path = req.resolve_output_file(&results_dir).ok_or_else(|| {
                AppError::ResultNotFound(format!(
                    "output file not found for result type '{}' in {}",
                    req.result_type.as_str(),
                                                 results_dir.display()
                ))
            })?;

            let mime = req.result_type.mime().unwrap_or("application/octet-stream");

            let bytes = tokio::fs::read(&file_path)
            .await
            .map_err(|e| AppError::Internal(format!("reading result file: {e}")))?;

            Ok((StatusCode::OK, [(header::CONTENT_TYPE, mime)], bytes).into_response())
        }

        ResultState::Queued | ResultState::Running | ResultState::Failed => {
            // FIX: req.job_id is Option<Uuid>; unwrap is safe here because
            // this endpoint is only reachable via /jobs/:id/results/:req_id,
            // meaning the ownership check above already confirmed job_id is Some.
            Ok((
                StatusCode::OK,
                Json(ResultStatusResponse {
                    result_request_id: req.id,
                    job_id:            job_id, // use the path param, already validated above
                    result_type:       req.result_type.as_str().to_string(),
                     state:             req.state.as_str().to_string(),
                     error:             req.error,
                     created_at:        req.created_at,
                     updated_at:        req.updated_at,
                }),
            )
            .into_response())
        }
    }
}

// =============================================================================
// Param validation
// =============================================================================

fn validate_params(
    result_type: ResultType,
    params: &Option<serde_json::Value>,
) -> ApiResult<()> {
    match result_type {
        ResultType::Timeseries => {
            let p = params.as_ref().ok_or_else(|| {
                AppError::Validation(
                    "timeseries requires params: { \"lat\": <f64>, \"lon\": <f64> }".to_string(),
                )
            })?;

            let lat = p.get("lat").and_then(|v| v.as_f64());
            let lon = p.get("lon").and_then(|v| v.as_f64());

            match (lat, lon) {
                (Some(lat), Some(lon)) => {
                    if !(-90.0..=90.0).contains(&lat) {
                        return Err(AppError::Validation(format!(
                            "lat must be in [-90, 90]; got {lat}"
                        )));
                    }
                    if !(-180.0..=180.0).contains(&lon) {
                        return Err(AppError::Validation(format!(
                            "lon must be in [-180, 180]; got {lon}"
                        )));
                    }
                    Ok(())
                }
                _ => Err(AppError::Validation(
                    "timeseries params must include numeric 'lat' and 'lon' fields".to_string(),
                )),
            }
        }

        ResultType::AiSummary | ResultType::Dem | ResultType::Model3d => {
            Err(AppError::Validation(format!(
                "result type '{}' is not yet implemented",
                result_type.as_str()
            )))
        }

        ResultType::Velocity => Ok(()),
    }
}
